'use strict';
/* Ma séance : toutes les séances d’1 h du manuel de 3e, sans date, et une séance complète */
const { chromium } = require('playwright');
const { install, makeState } = require('./mock-supabase');
const SHOTS = process.env.SHOTS || '/tmp/claude-0/-home-claude/352bfbd7-cd9f-5fb4-ba56-436b6cfb21f0/scratchpad/shots';
require('fs').mkdirSync(SHOTS, { recursive: true });
const BASE = process.env.BASE || 'http://127.0.0.1:8765/dist/maseance/index.html';
let pass = 0, fail = 0;
function ok(c, msg) { if (c) { pass++; console.log('  ✓ ' + msg); } else { fail++; console.log('  ✗ ' + msg); } }
(async () => {
  const browser = await chromium.launch(); const st = makeState();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 }, locale: 'fr-FR' }); await install(ctx, st);
  const page = await ctx.newPage(); const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  page.on('console', (m) => { if (m.type() === 'error' && !/status of (400|404)/.test(m.text())) errors.push('console: ' + m.text()); });
  await page.goto(BASE); await page.waitForSelector('.auth-card'); await page.fill('input[type=email]', 'prof@test.fr'); await page.fill('input[type=password]', 'secret12'); await page.click('.auth-card button[type=submit]');
  await page.waitForSelector('.top');
  const cid = await page.evaluate(() => DB.create('fs_classes', { nom: '3PM1', niveau_id: 'pm', groupement: 'A', avec_pc: false, poursuite: false, metier: '', annee_scolaire: '2026-2027', couleur: '#2B4C7E', creneaux: [{ jour: 1, debut: '08:00', fin: '09:00' }], notes: '' }).id);
  await page.goto(BASE + '#/classe/' + cid); await page.waitForSelector('button:has-text("Séance depuis")');
  await page.click('button:has-text("Séance depuis")'); await page.waitForSelector('.modal .tpl');
  const btn = page.locator('.modal button:has-text("Tout le manuel")'); await btn.waitFor();
  const label = await btn.innerText(); console.log('     ' + label);
  await btn.click(); await page.waitForTimeout(300);
  const cnt = await page.locator('.modal .tpl .muted.small', { hasText: 'sélectionnée' }).first().innerText();
  ok(/62 séances sélectionnées/.test(cnt), 'toutes les séances sélectionnées : ' + cnt);
  await page.locator('.modal label.check', { hasText: 'Proposer des dates' }).locator('input').uncheck();
  await page.click('.modal button:has-text("Créer les séances sélectionnées")'); await page.waitForTimeout(1500);
  const rs = await page.evaluate(() => DB.list('fs_seances').map((s) => ({ id: s.id, t: s.titre, d: s.date_prevue || null, m: s.duree_min, ty: s.type, n: (s.data.items || []).length, ex: (s.data.manuel || {}).exos, no: (s.data.manuel || {}).notions })));
  ok(rs.length === 62, rs.length + ' séances créées (42 notions + 10 défis + 10 contrôles)');
  ok(rs.every((r) => !r.d), 'aucune séance n’a de date');
  ok(rs.every((r) => r.m === 60), 'toutes durent 1 h');
  console.log(rs.slice(0, 8).map((r) => '     ' + r.t + ' [' + r.ty + '] exos ' + JSON.stringify(r.ex)).join('\n'));
  const fs = require('fs'); fs.writeFileSync(SHOTS + '/e12-liste.json', JSON.stringify(rs, null, 1));
  const one = rs.find((r) => /Pourcentages d’évolution/.test(r.t));
  ok(!!one, 'séance « Pourcentages d’évolution » trouvée : ' + (one && one.t));
  await page.goto(BASE + '#/seance/' + one.id); await page.waitForSelector('h1, .seance-head, .qbar', { timeout: 8000 }); await page.waitForTimeout(600);
  await page.screenshot({ path: SHOTS + '/e12-seance.png', fullPage: true });
  const html = await page.evaluate((id) => Exp.seanceHtml(DB.byId('fs_seances', id)), one.id);
  const full = await page.evaluate((id) => { const s = DB.byId('fs_seances', id); return Exp.htmlPage(s.titre, Exp.seanceHtml(s)); }, one.id);
  fs.writeFileSync(SHOTS + '/e12-seance.html', full);
  const pg2 = await ctx.newPage(); await pg2.setContent(full); await pg2.pdf({ path: SHOTS + '/Seance_3e_complete_exemple.pdf', format: 'A4', margin: { top: '15mm', bottom: '15mm', left: '14mm', right: '14mm' }, printBackground: true }); await pg2.close();
  const ph = await page.evaluate((id) => DB.byId('fs_seances', id).data.phases.reduce((a, x) => a + x.duree, 0), one.id);
  ok(ph === 60, 'le déroulé occupe exactement 60 min (' + ph + ')');
  const tot = await page.evaluate(() => DB.list('fs_seances').filter((s) => s.type === 'cours').map((s) => s.data.phases.reduce((a, x) => a + x.duree, 0)));
  ok(tot.length === 42 && tot.every((x) => x === 60), '42 séances de notion, toutes à 60 min de déroulé');
  ok(/Objectif/.test(html) && /Je retiens/.test(html) && /Exercices du manuel/.test(html) && /Trace écrite|Titre :/.test(html), 'export complet : objectif, déroulé, exercices, trace écrite');
  ok(errors.length === 0, 'aucune erreur console (' + errors.join(' | ') + ')');
  console.log('\n' + pass + ' ✓  ' + fail + ' ✗'); await browser.close(); process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
